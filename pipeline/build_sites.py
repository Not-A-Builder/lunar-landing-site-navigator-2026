#!/usr/bin/env python3
"""Build src/data/sites.json from data/source/sites-research.json (sourced site records).

Every record in the research file carries sourceUrl + sourceQuote copied from a fetched source
(LROC anthropogenic-objects shapefile on PDS, USGS Gazetteer, LROC RDR pages, NASA pages).
Every listed site must have a coordinate copied from a cited source (LOGS D-038). Records without one
are not listed; they go to "excluded" with the reason, and return automatically once a cited
coordinate is added to the research file.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "source" / "sites-research.json"
OUT = ROOT / "src" / "data" / "sites.json"

ARTEMIS_NOTE = ("One of the nine south-pole candidate landing regions NASA announced in Oct 2024, when they were "
                "chosen for Artemis III. In Feb 2026 NASA made Artemis III an Earth-orbit test flight and moved the first "
                "crewed landing to Artemis IV (planned 2028); NASA has not published a revised region list. Pin = centre "
                "of LROC's NAC mosaic for this candidate site, not an official region centre.")


def slug(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")[:60]


def main():
    recs = json.loads(SRC.read_text())
    out, excluded, seen = [], [], set()
    for r in recs:
        base = slug(r["name"].split(" - target")[0].split("(")[0])
        if r["group"] == "feature":
            base = "feature-" + base
        sid, n = base, 2
        while sid in seen:
            sid, n = f"{base}-{n}", n + 1
        seen.add(sid)
        has = r.get("lat") is not None and r.get("lon") is not None
        notes = r.get("notes") or ""
        status = r.get("status")
        group = "artemis-region" if r["group"] == "artemis-iii-region" else r["group"]
        if group == "artemis-region":
            notes = (ARTEMIS_NOTE + (" " + notes if notes else "")).strip()
            status = "candidate region"
        if not (has and r.get("sourceUrl")):
            excluded.append({
                "name": r["name"],
                "group": group,
                "mission": r.get("mission"),
                "sourceUrl": r.get("sourceUrl"),
                "reason": r.get("excludedReason") or "No published coordinate found.",
                "notes": r.get("notes"),
            })
            continue
        out.append({
            "id": sid,
            "name": r["name"],
            "group": group,
            "kind": r.get("kind") or "point",
            "lat": r.get("lat"),
            "lon": r.get("lon"),
            "polygon": r.get("polygon"),
            "mission": r.get("mission"),
            "date": r.get("date"),
            "status": status,
            "sourceUrl": r.get("sourceUrl"),
            "sourceQuote": r.get("sourceQuote"),
            "verification": "verified",
            "notes": notes or None,
        })
    OUT.write_text(json.dumps({
        "_readme": "Generated by pipeline/build_sites.py from data/source/sites-research.json. Do not hand-edit.",
        "sites": out,
        "excluded": excluded,
    }, ensure_ascii=False, indent=1) + "\n")
    print(f"wrote {len(out)} sites with cited coordinates; {len(excluded)} excluded (no cited coordinate)")


if __name__ == "__main__":
    main()
